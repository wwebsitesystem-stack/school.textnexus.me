export default {
  async fetch(request, env, ctx) {
    const corsHeaders = {
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "POST, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type",
    };

    if (request.method === "OPTIONS") return new Response(null, { headers: corsHeaders });
    if (request.method !== "POST") return new Response("Send a POST request", { status: 405, headers: corsHeaders });

    try {
      const { prompt, subdomain } = await request.json();

      if (!prompt) {
        return new Response(JSON.stringify({ error: "Missing prompt." }), {
          status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" }
        });
      }

      if (!env.AI) {
        return new Response(JSON.stringify({ error: "Cloudflare AI binding 'AI' is not configured." }), {
          status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" }
        });
      }

      // 1. Generate website code using Workers AI
      let aiResponse;
      try {
        aiResponse = await env.AI.run('@cf/openai/gpt-oss-120b', {
          messages: [
            { 
              role: "system", 
              content: "You are an expert full-stack developer and AI assistant. Return ONLY valid, clean, fully responsive HTML/CSS code without markdown code blocks or conversational text." 
            },
            { role: "user", content: prompt }
          ]
        });
      } catch (aiErr) {
        throw new Error("Workers AI generation failed: " + aiErr.message);
      }

      // Robust response parsing for different Cloudflare AI model formats
      let replyText = "";
      if (typeof aiResponse === "string") {
        replyText = aiResponse;
      } else if (aiResponse && aiResponse.response) {
        replyText = aiResponse.response;
      } else if (aiResponse && aiResponse.choices && aiResponse.choices[0]?.message?.content) {
        replyText = aiResponse.choices[0].message.content;
      } else {
        replyText = JSON.stringify(aiResponse);
      }

      if (!replyText || replyText.trim() === "") {
        replyText = "<h1>Error: Empty response generated by AI model.</h1>";
      }

      // If a subdomain/builder request is made, automate GitHub repo, Pages, & DNS creation
      if (subdomain) {
        const repoName = `nexus-${subdomain}`;
        const customDomain = `${subdomain}.textnexus.me`;
        const siteUrl = `https://${customDomain}`;

        // 2. Automate GitHub Repository Creation, Code Push, CNAME, & Pages Activation
        if (env.GITHUB_TOKEN) {
          try {
            const userRes = await fetch("https://api.github.com/user", {
              headers: { 
                "Authorization": `Bearer ${env.GITHUB_TOKEN}`,
                "User-Agent": "TextNexus-Worker",
                "Accept": "application/vnd.github+json"
              }
            });
            const userData = await userRes.json();
            const githubUsername = userData.login;

            if (githubUsername) {
              // Create Repository
              await fetch("https://api.github.com/user/repos", {
                method: "POST",
                headers: {
                  "Authorization": `Bearer ${env.GITHUB_TOKEN}`,
                  "User-Agent": "TextNexus-Worker",
                  "Accept": "application/vnd.github+json",
                  "Content-Type": "application/json"
                },
                body: JSON.stringify({
                  name: repoName,
                  description: `Generated by TextNexus AI for prompt: ${prompt}`,
                  private: false,
                  auto_init: true
                })
              });

              // Wait 2 seconds for GitHub repo initialization
              await new Promise(resolve => setTimeout(resolve, 2000));

              // Encode and push index.html
              const encodedHTML = btoa(unescape(encodeURIComponent(replyText)));
              await fetch(`https://api.github.com/repos/${githubUsername}/${repoName}/contents/index.html`, {
                method: "PUT",
                headers: {
                  "Authorization": `Bearer ${env.GITHUB_TOKEN}`,
                  "User-Agent": "TextNexus-Worker",
                  "Accept": "application/vnd.github+json",
                  "Content-Type": "application/json"
                },
                body: JSON.stringify({
                  message: "Initial commit generated by TextNexus AI",
                  content: encodedHTML
                })
              });

              // Encode and push CNAME file for Custom Domain
              const encodedCNAME = btoa(unescape(encodeURIComponent(customDomain)));
              await fetch(`https://api.github.com/repos/${githubUsername}/${repoName}/contents/CNAME`, {
                method: "PUT",
                headers: {
                  "Authorization": `Bearer ${env.GITHUB_TOKEN}`,
                  "User-Agent": "TextNexus-Worker",
                  "Accept": "application/vnd.github+json",
                  "Content-Type": "application/json"
                },
                body: JSON.stringify({
                  message: "Add custom domain CNAME",
                  content: encodedCNAME
                })
              });

              // Enable GitHub Pages and assign the main branch & custom domain
              await fetch(`https://api.github.com/repos/${githubUsername}/${repoName}/pages`, {
                method: "POST",
                headers: {
                  "Authorization": `Bearer ${env.GITHUB_TOKEN}`,
                  "User-Agent": "TextNexus-Worker",
                  "Accept": "application/vnd.github+json",
                  "Content-Type": "application/json"
                },
                body: JSON.stringify({
                  source: {
                    branch: "main",
                    path: "/"
                  },
                  cname: customDomain
                })
              });
            }
          } catch (ghErr) {
            console.error("GitHub integration error:", ghErr);
          }
        }

        // 3. Automate Cloudflare DNS Subdomain Creation
        if (env.CLOUDFLARE_API_TOKEN && env.CLOUDFLARE_ZONE_ID) {
          try {
            await fetch(`https://api.cloudflare.com/client/v4/zones/${env.CLOUDFLARE_ZONE_ID}/dns_records`, {
              method: "POST",
              headers: {
                "Authorization": `Bearer ${env.CLOUDFLARE_API_TOKEN}`,
                "Content-Type": "application/json"
              },
              body: JSON.stringify({
                type: "CNAME",
                name: customDomain,
                content: "textnexus.me",
                proxied: true
              })
            });
          } catch (dnsErr) {
            console.error("DNS automation error:", dnsErr);
          }
        }

        return new Response(JSON.stringify({ 
          reply: replyText,
          siteUrl: siteUrl,
          code: replyText,
          repo: repoName
        }), {
          status: 200, 
          headers: { ...corsHeaders, "Content-Type": "application/json" }
        });
      }

      // Default Playground text response
      return new Response(JSON.stringify({ reply: replyText }), {
        status: 200, 
        headers: { ...corsHeaders, "Content-Type": "application/json" }
      });

    } catch (err) {
      return new Response(JSON.stringify({ error: err.message || "An unexpected error occurred." }), {
        status: 500, 
        headers: { ...corsHeaders, "Content-Type": "application/json" }
      });
    }
  }
};
